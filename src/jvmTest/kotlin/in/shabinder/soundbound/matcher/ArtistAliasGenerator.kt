package `in`.shabinder.soundbound.matcher

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File
import kotlin.test.Test

/**
 * Regenerates [ArtistAliasData] (skipped unless ALIAS_GROUPS is set). Inputs, with the scripts in `aliasdata/`:
 * 1. `curl -s https://data.metabrainz.org/pub/musicbrainz/data/json-dumps/<date>/artist.tar.xz | xz -dc |
 *    python3 -I extract_dump.py > dump_cross.jsonl` (artists whose names mix Latin and non-Latin scripts);
 * 2. `python3 -I popularity.py dump_cross.jsonl > pop.json` (ListenBrainz listen counts);
 * 3. `python3 -I select.py dump_cross.jsonl pop.json 300000 10000 > groups.json` (Latin-named artists with 300k+
 *    listens, non-Latin-named ones with 10k+, store-facing names first);
 * 4. `ALIAS_GROUPS=groups.json ./gradlew jvmTest --tests '*ArtistAliasGenerator*' --rerun`.
 */
class ArtistAliasGenerator {
    private val MAX_LATIN = 2

    @Test fun generate() {
        val path = System.getenv("ALIAS_GROUPS") ?: return
        val limit = System.getenv("ALIAS_LIMIT")?.toInt() ?: Int.MAX_VALUE
        val out = File(System.getenv("ALIAS_OUT") ?: "src/commonMain/kotlin/in.shabinder.soundbound/matcher/ArtistAliasData.kt")
        val seen = HashSet<String>()
        val lines = ArrayList<String>()
        var scanned = 0
        for (g in Json.parseToJsonElement(File(path).readText()).jsonArray) {
            if (lines.size >= limit) break
            scanned++
            val names = g.jsonObject["names"]!!.jsonArray.map { it.jsonPrimitive.content }
            // One representative per key; a key already owned by a more listened artist stays with it.
            val byKey = LinkedHashMap<String, String>()
            for (n in names) ArtistAliases.key(n).let { k -> if (k.length >= 2 && k !in seen) byKey.putIfAbsent(k, n) }
            if (byKey.size < 2) continue
            // Latin-only spellings of a Latin name ("Die Beatles") are not cross-script and are where unrelated artists
            // collide; a short Latin alias ("Lam" for George Lam) names too many other artists. Every non-Latin name is
            // kept; a Latin one only when the plain matcher misses it against some kept non-Latin name (Faye Wong vs 王菲,
            // but not "Wang Fei", which the romanizer already reads out of 王菲).
            val primary = names.first()
            val latinPrimary = ArtistAliases.key(primary).all { it.code < 0x370 }
            // Every non-Latin name is kept (plain matching is not transitive: 동방신기 ~ "東方神起 (THSK)" by sound key, yet
            // 동방신기 vs TVXQ! fails). A Latin name is kept only when the plain matcher misses it against some kept
            // non-Latin one (Faye Wong vs 王菲, not "Wang Fei"), at most MAX_LATIN of them.
            // ponytail: MAX_LATIN caps the long tail of romanization variants; raise it if recall needs them.
            val keep = LinkedHashMap<String, String>()
            for ((k, n) in byKey) if (n == primary || k.any { it.code >= 0x370 }) keep[k] = n
            var latinKept = 0
            for ((k, n) in byKey) {
                if (k in keep || latinPrimary || k.length < 4 || latinKept >= MAX_LATIN) continue
                if (keep.values.none { it != n && RecordingMatch.artistSimilarity(listOf(it), listOf(n), aliases = false) < RecordingMatch.ARTIST_THRESHOLD }) continue
                keep[k] = n
                latinKept++
            }
            if (keep.values.distinct().size < 2) continue
            seen += keep.keys
            lines += keep.keys.joinToString("|")
        }
        val table = ArtistAliasCodec.encode(lines.joinToString("\n"))
        check(ArtistAliasCodec.decode(table) == lines.joinToString("\n"))
        out.writeText(buildString {
            append("package `in`.shabinder.soundbound.matcher\n\n")
            append("// Generated by ArtistAliasGenerator (jvmTest) from the MusicBrainz artist dump (CC0) ranked by ListenBrainz\n")
            append("// listen counts (CC0), encoded by ArtistAliasCodec. Do not edit by hand.\n")
            // A JVM string constant holds at most 65,535 UTF-8 bytes and the compiler folds "a" + "b", so the table is
            // several literals joined at first use.
            append("internal object ArtistAliasData {\n    val TABLE: String get() = listOf(\n")
            for (part in table.chunked(30_000)) {
                val chunks = part.chunked(110)
                chunks.forEachIndexed { i, c ->
                    append(if (i == 0) "        \"" else "            \"").append(c).append('"').append(if (i < chunks.size - 1) " +\n" else ",\n")
                }
            }
            append("    ).joinToString(\"\")\n}\n")
        })
        println("alias groups: ${lines.size} of $scanned scanned, ${table.length} chars encoded")
    }
}
